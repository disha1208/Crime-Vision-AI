"""
Forensic PDF Report Generator for CrimeVision AI.
Generates court-ready and investigative PDF reports using ReportLab.
"""
from datetime import datetime
from pathlib import Path
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.units import inch
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable, KeepTogether
)
from reportlab.pdfgen import canvas

class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to dynamically compute and print 'Page X of Y' and header/footer.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_header_footer(num_pages)
            super().showPage()
        super().save()

    def draw_header_footer(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))

        # Header
        self.drawString(54, 11 * inch - 36, "CRIMEVISION AI  |  FORENSIC EXAMINATION & EVIDENCE REPORT")
        self.drawRightString(8.5 * inch - 54, 11 * inch - 36, "OFFICIAL LAW ENFORCEMENT USE ONLY")
        self.setStrokeColor(colors.HexColor("#cbd5e1"))
        self.setLineWidth(0.5)
        self.line(54, 11 * inch - 42, 8.5 * inch - 54, 11 * inch - 42)

        # Footer
        self.line(54, 46, 8.5 * inch - 54, 46)
        self.drawString(54, 32, "CONFIDENTIAL  *  CHAIN OF CUSTODY VERIFIED VIA SHA-256")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(8.5 * inch - 54, 32, page_str)
        self.restoreState()


class ForensicReportGenerator:
    @staticmethod
    def generate_case_report(case_dict: dict, evidence_list: list, timeline_list: list, output_path: Path) -> str:
        """
        Builds the complete forensic PDF document.
        """
        output_path.parent.mkdir(parents=True, exist_ok=True)
        doc = SimpleDocTemplate(
            str(output_path),
            pagesize=letter,
            leftMargin=54,
            rightMargin=54,
            topMargin=54,
            bottomMargin=54
        )

        styles = getSampleStyleSheet()
        
        # Custom styles
        title_style = ParagraphStyle(
            'DocTitle',
            parent=styles['Heading1'],
            fontName='Helvetica-Bold',
            fontSize=20,
            leading=24,
            textColor=colors.HexColor('#0f172a')
        )
        subtitle_style = ParagraphStyle(
            'DocSub',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=10,
            leading=14,
            textColor=colors.HexColor('#475569')
        )
        h2_style = ParagraphStyle(
            'SectionH2',
            parent=styles['Heading2'],
            fontName='Helvetica-Bold',
            fontSize=13,
            leading=16,
            textColor=colors.HexColor('#1e3a8a'),
            spaceBefore=14,
            spaceAfter=6
        )
        body_style = ParagraphStyle(
            'CustomBody',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=9,
            leading=13,
            textColor=colors.HexColor('#1e293b')
        )
        hash_style = ParagraphStyle(
            'HashText',
            parent=styles['Normal'],
            fontName='Courier',
            fontSize=7.5,
            leading=9,
            textColor=colors.HexColor('#0f172a')
        )
        disclaimer_style = ParagraphStyle(
            'Disclaimer',
            parent=styles['Normal'],
            fontName='Helvetica-Oblique',
            fontSize=8,
            leading=11,
            textColor=colors.HexColor('#475569')
        )

        story = []

        # Header Title Block
        story.append(Paragraph("FORENSIC EVIDENCE & TIMELINE REPORT", title_style))
        story.append(Spacer(1, 4))
        generated_date = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")
        story.append(Paragraph(f"Generated by CrimeVision AI Platform  *  {generated_date}", subtitle_style))
        story.append(Spacer(1, 10))

        # Classification Banner
        banner_data = [
            [
                Paragraph("<b>CLASSIFICATION:</b> LAW ENFORCEMENT SENSITIVE", ParagraphStyle('B1', fontName='Helvetica-Bold', fontSize=8, textColor=colors.HexColor('#991b1b'))),
                Paragraph("<b>CHAIN OF CUSTODY:</b> SECURED (SHA-256)", ParagraphStyle('B2', fontName='Helvetica-Bold', fontSize=8, textColor=colors.HexColor('#1e3a8a'), alignment=2))
            ]
        ]
        banner_table = Table(banner_data, colWidths=[280, 224])
        banner_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#f1f5f9')),
            ('PADDING', (0, 0), (-1, -1), 6),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor('#cbd5e1')),
        ]))
        story.append(banner_table)
        story.append(Spacer(1, 14))

        # Section 1: Case Summary
        story.append(Paragraph("1. INVESTIGATION CASE DOSSIER", h2_style))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#cbd5e1'), spaceAfter=8))

        case_table_data = [
            [Paragraph("<b>Case Number:</b>", body_style), Paragraph(case_dict.get('case_number', 'N/A'), body_style),
             Paragraph("<b>Status:</b>", body_style), Paragraph(case_dict.get('status', 'Active'), body_style)],
            [Paragraph("<b>Case Title:</b>", body_style), Paragraph(case_dict.get('title', 'N/A'), body_style),
             Paragraph("<b>Priority:</b>", body_style), Paragraph(case_dict.get('priority', 'Medium'), body_style)],
            [Paragraph("<b>Incident Date:</b>", body_style), Paragraph(case_dict.get('incident_date', 'N/A'), body_style),
             Paragraph("<b>Lead Investigator:</b>", body_style), Paragraph(case_dict.get('lead_investigator', 'Unassigned'), body_style)],
            [Paragraph("<b>Location:</b>", body_style), Paragraph(case_dict.get('location', 'N/A'), body_style),
             Paragraph("<b>Evidence Count:</b>", body_style), Paragraph(str(len(evidence_list)), body_style)],
        ]
        case_table = Table(case_table_data, colWidths=[100, 160, 110, 134])
        case_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#f8fafc')),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
            ('PADDING', (0, 0), (-1, -1), 5),
        ]))
        story.append(case_table)
        story.append(Spacer(1, 8))

        if case_dict.get('description'):
            story.append(Paragraph(f"<b>Case Narrative:</b> {case_dict.get('description')}", body_style))
            story.append(Spacer(1, 10))

        # Section 2: Evidence Registry & Cryptographic Hashes
        story.append(Paragraph("2. EVIDENCE REGISTRY & INTEGRITY HASHES", h2_style))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#cbd5e1'), spaceAfter=8))

        if not evidence_list:
            story.append(Paragraph("<i>No evidence items registered in this case dossier.</i>", body_style))
        else:
            ev_headers = ["Item", "Type", "Original Filename", "SHA-256 Hash", "Status"]
            ev_rows = [[
                Paragraph(f"<b>{h}</b>", ParagraphStyle('TH', fontName='Helvetica-Bold', fontSize=8, textColor=colors.white))
                for h in ev_headers
            ]]

            for idx, ev in enumerate(evidence_list):
                row = [
                    Paragraph(f"#{idx+1}", body_style),
                    Paragraph(ev.get('file_type', '').upper(), body_style),
                    Paragraph(ev.get('filename', ''), body_style),
                    Paragraph(ev.get('sha256_hash', ''), hash_style),
                    Paragraph(ev.get('status', 'Pending'), body_style)
                ]
                ev_rows.append(row)

            ev_table = Table(ev_rows, colWidths=[30, 48, 110, 250, 66])
            ev_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#1e3a8a')),
                ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
                ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#f8fafc')]),
                ('PADDING', (0, 0), (-1, -1), 4),
            ]))
            story.append(ev_table)

        story.append(Spacer(1, 14))

        # Section 3: Multimodal Forensic Analysis Findings
        story.append(Paragraph("3. MULTIMODAL FORENSIC ANALYSIS FINDINGS", h2_style))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#cbd5e1'), spaceAfter=8))

        analyzed_items = [e for e in evidence_list if e.get('analysis')]
        if not analyzed_items:
            story.append(Paragraph("<i>No forensic analysis has been executed on the current evidence set.</i>", body_style))
        else:
            for idx, item in enumerate(analyzed_items):
                ana = item.get('analysis', {})
                sim_badge = " [SIMULATED / DEMO MODE]" if ana.get('is_simulated') else " [REAL AI INFERENCE]"
                
                story.append(Paragraph(
                    f"<b>Evidence Item #{idx+1}: {item.get('filename')}</b> ({item.get('file_type').upper()}) — <i>Model: {ana.get('model_used')}{sim_badge}</i>",
                    ParagraphStyle('ItemH', fontName='Helvetica-Bold', fontSize=9, textColor=colors.HexColor('#1e293b'))
                ))
                story.append(Spacer(1, 3))

                if ana.get('summary'):
                    story.append(Paragraph(f"<b>Summary:</b> {ana.get('summary')}", body_style))
                if ana.get('scene_description'):
                    story.append(Paragraph(f"<b>Scene Description:</b> {ana.get('scene_description')}", body_style))
                
                # Detected Objects
                objects = ana.get('detected_objects', [])
                if objects:
                    obj_strs = [f"{o.get('label')} ({int(o.get('confidence',0)*100)}% conf)" for o in objects]
                    story.append(Paragraph(f"<b>Detected Objects / Entities:</b> {', '.join(obj_strs)}", body_style))

                # Audio Transcription
                if ana.get('transcription'):
                    story.append(Paragraph(f"<b>Transcription:</b> {ana.get('transcription')}", body_style))

                story.append(Spacer(1, 8))

        story.append(Spacer(1, 10))

        # Section 4: Unified Incident Timeline
        story.append(Paragraph("4. UNIFIED CHRONOLOGICAL INCIDENT TIMELINE", h2_style))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#cbd5e1'), spaceAfter=8))

        if not timeline_list:
            story.append(Paragraph("<i>No timeline markers have been recorded for this case.</i>", body_style))
        else:
            tl_headers = ["Time Marker", "Source", "Event Title", "Details / Observations"]
            tl_rows = [[
                Paragraph(f"<b>{h}</b>", ParagraphStyle('TH2', fontName='Helvetica-Bold', fontSize=8, textColor=colors.white))
                for h in tl_headers
            ]]

            for t in timeline_list:
                conf_text = f" ({int(t.get('confidence')*100)}%)" if t.get('confidence') else ""
                tl_rows.append([
                    Paragraph(f"<b>{t.get('timestamp_str')}</b>", body_style),
                    Paragraph(t.get('source_type', '').upper(), body_style),
                    Paragraph(f"{t.get('title')}{conf_text}", body_style),
                    Paragraph(t.get('description', ''), body_style)
                ])

            tl_table = Table(tl_rows, colWidths=[65, 55, 160, 224])
            tl_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#0f172a')),
                ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
                ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#f8fafc')]),
                ('PADDING', (0, 0), (-1, -1), 4),
            ]))
            story.append(tl_table)

        story.append(Spacer(1, 14))

        # Section 5: Forensic Integrity, Limitations & Legal Disclaimer
        story.append(KeepTogether([
            Paragraph("5. FORENSIC INTEGRITY, LIMITATIONS & LEGAL DISCLAIMER", h2_style),
            HRFlowable(width="100%", thickness=1, color=colors.HexColor('#cbd5e1'), spaceAfter=8),
            Paragraph(
                "<b>1. Chain of Custody:</b> All evidence items cataloged in this report have been hashed via cryptographic "
                "SHA-256 standard at the moment of ingestion. Hashes can be verified independently against evidentiary storage.<br/>"
                "<b>2. Multimodal AI Assistance:</b> Automated detections (RT-DETR, CLIP, BLIP, Whisper) represent algorithmic "
                "hypotheses and probabilistic confidence indices. They do NOT constitute conclusive proof of guilt, intent, or criminal liability.<br/>"
                "<b>3. Demo Mode Disclosures:</b> Analysis executed in Demo Mode uses simulated forensic heuristics for demonstrative evaluation. "
                "Production judicial proceedings mandate real verified model inference with certified weights and human forensic validation.<br/>"
                "<b>4. Examiner Corroboration:</b> All electronic evidence, timeline markers, and acoustic transcripts must be reviewed "
                "and signed by an accredited digital forensics examiner prior to formal submission in judicial proceedings.",
                disclaimer_style
            ),
            Spacer(1, 16),
            # Signature block
            Table([
                [
                    Paragraph("<b>Forensic Examiner Signature:</b> ___________________________", body_style),
                    Paragraph("<b>Date of Verification:</b> ___________________________", body_style)
                ]
            ], colWidths=[250, 254])
        ]))

        doc.build(story, canvasmaker=NumberedCanvas)
        return str(output_path)
